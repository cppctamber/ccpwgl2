require('./test-attachment-lights-runtime.js');
const assert=require('node:assert/strict');
const {tw2}=require('../dist/ccpwgl2_int.js');
const SOF=tw2.GetClass('EveSOFData');
const data=new SOF();
data.generic=new (tw2.GetClass('EveSOFDataGeneric'))();
assert.equal(data.globalVideoBrightnessModifier,5);
const source=[0,2,3].map(usage=>tw2.GetClass('EveSOFDataHullPlaneSet').from({name:'usage'+usage,usage,items:[tw2.GetClass('EveSOFDataHullPlaneSetItem').from({color:[0.25,0.5,0.75,0.5]})]}));
const factionColor=[0.5,0.25,0.125,0.5];
const faction={FindPlaneSetByGroupIndex:()=>({color:factionColor})};
const obj={attachments:[]},sof={hull:{sof6:false,isSkinned:false,planeSets:source},faction};
const setup=()=>SOF.SetupPlaneSets(data,obj,sof,data._options);
setup();
assert.deepEqual(Array.from(obj.attachments[0].items[0].color),factionColor);
for(const p of obj.attachments.slice(1)) assert.deepEqual(Array.from(p.items[0].color),[2.5,1.25,0.625,0.5]);
setup();
for(const p of obj.attachments.slice(1)) assert.deepEqual(Array.from(p.items[0].color),[2.5,1.25,0.625,0.5]);
data.globalVideoBrightnessModifier=2;setup();
for(const p of obj.attachments.slice(1)) assert.deepEqual(Array.from(p.items[0].color),[1,0.5,0.25,0.5]);
for(const p of source) assert.deepEqual(Array.from(p.items[0].color),[0.25,0.5,0.75,0.5]);
console.log('SOF video brightness: both video usages, alpha, non-video colour, source preservation and repeated rebuild verified');
